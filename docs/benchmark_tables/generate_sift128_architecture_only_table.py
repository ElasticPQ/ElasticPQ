#!/usr/bin/env python3
"""Generate the paper table for the SIFT1M/128b architecture-only control."""

from __future__ import annotations

import argparse
import csv
import json
import statistics
from collections import defaultdict
from pathlib import Path


ORDER = (
    "learned_architecture",
    "learned_dims_balanced_bits",
    "balanced_dims_dp_bits_matched_m",
    "balanced_dims_balanced_bits_matched_m",
    "grid_best_dp_bits",
)
LABELS = {
    "learned_architecture": ("EPQ searched descriptor", "Heterogeneous", "DP"),
    "learned_dims_balanced_bits": ("Fixed-$M$ control", "Heterogeneous", "Equal"),
    "balanced_dims_dp_bits_matched_m": ("Fixed-$M$ control", "Balanced", "DP"),
    "balanced_dims_balanced_bits_matched_m": ("Fixed-$M$ control", "Balanced", "Equal"),
    "grid_best_dp_bits": ("Balanced proxy-grid winner", "Balanced", "DP"),
}
METRICS = (
    "reconstruction_error",
    "recall10",
)


def load_rows(path: Path) -> dict[str, list[dict[str, str]]]:
    with path.open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    if any(int(row["exit_status"]) != 0 for row in rows):
        raise RuntimeError("result CSV contains failed runs")
    grouped: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        grouped[row["architecture"]].append(row)
    if set(grouped) != set(ORDER):
        raise RuntimeError(f"architecture mismatch: {set(grouped)}")
    seed_sets = [{int(row["init_seed"]) for row in grouped[name]} for name in ORDER]
    if any(seeds != seed_sets[0] for seeds in seed_sets[1:]):
        raise RuntimeError(f"unpaired initialization seeds: {seed_sets}")
    if len(seed_sets[0]) != 10:
        raise RuntimeError(f"expected 10 shared seeds, found {len(seed_sets[0])}")
    for name in ORDER:
        arch_rows = grouped[name]
        if len(arch_rows) != 10:
            raise RuntimeError(f"expected 10 rows for {name}, found {len(arch_rows)}")
        if {row["init_mode"] for row in arch_rows} != {"matched_physical"}:
            raise RuntimeError(f"initialization mismatch for {name}")
        if {int(row["main_bits"]) for row in arch_rows} != {128}:
            raise RuntimeError(f"bit-budget mismatch for {name}")
        if {int(row["train_rows"]) for row in arch_rows} != {100000}:
            raise RuntimeError(f"training-row mismatch for {name}")
    return grouped


def aggregate(rows: list[dict[str, str]], key: str) -> tuple[float, float]:
    values = [float(row[key]) for row in rows]
    return statistics.mean(values), statistics.stdev(values)


def architecture_table(grouped: dict[str, list[dict[str, str]]]) -> str:
    aggregates = {
        name: {metric: aggregate(grouped[name], metric) for metric in METRICS}
        for name in ORDER
    }

    def mean_sd(name: str, metric: str, digits: int) -> str:
        mean, sd = aggregates[name][metric]
        return f"${mean:.{digits}f}\\pm{sd:.{digits}f}$"

    lines = [
        "% Generated by docs/benchmark_tables/generate_sift128_architecture_only_table.py",
        "\\begin{table}[H]",
        "\\centering",
        "\\scriptsize",
        "\\caption{Decoupled product-descriptor control for EPQ w/o tail on SIFT1M/128b.",
        "The four $M=12$ rows form a $2\\times2$ dimensions--allocation control;",
        "the last row is selected over balanced $M=11,\\ldots,20$ by the same",
        "proxy $J^*$. Values are mean$\\pm$standard deviation over ten shared",
        "physical $W_0$ seeds. Sharing $W_0$ breaks each descriptor's natural",
        "coupling to its searched or neutral orientation, so this isolates descriptor",
        "shape rather than complete pipelines. Lower $J$",
        "and higher R@10 are better.}",
        "\\label{tab:architecture-only}",
        "\\resizebox{\\columnwidth}{!}{%",
        "\\begin{tabular}{lcllrr}",
        "\\toprule",
        "Architecture selection & $M$ & Dimensions & Bit allocation & $J$ & R@10 \\\\",
        "\\midrule",
    ]
    for name in ORDER:
        row0 = grouped[name][0]
        selection, dimensions, bits = LABELS[name]
        lines.append(
            f"{selection} & {int(row0['group_count'])} & {dimensions} & {bits} & "
            f"{mean_sd(name, 'reconstruction_error', 0)} & "
            f"{mean_sd(name, 'recall10', 4)} \\\\"
        )
    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}}",
            "\\end{table}",
        ]
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, required=True)
    parser.add_argument("--paper-generated", type=Path, required=True)
    args = parser.parse_args()

    grouped = load_rows(args.results)
    args.paper_generated.mkdir(parents=True, exist_ok=True)
    output = args.paper_generated / "sift128_architecture_only_table.tex"
    output.write_text(architecture_table(grouped))
    print(json.dumps({"architecture_table": str(output)}))


if __name__ == "__main__":
    main()
