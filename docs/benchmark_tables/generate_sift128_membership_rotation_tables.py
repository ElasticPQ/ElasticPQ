#!/usr/bin/env python3
"""Generate paper LaTeX tables for the SIFT1M membership/rotation control."""

from __future__ import annotations

import argparse
import csv
import json
import statistics
from collections import defaultdict
from pathlib import Path


def load_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    if len(rows) != 86:
        raise RuntimeError(f"expected 86 result rows, found {len(rows)}")
    if any(int(row["exit_status"]) != 0 for row in rows):
        raise RuntimeError("result CSV contains failed runs")
    signatures = {
        (row["group_count"], row["group_sizes"], row["group_bits"], row["main_bits"])
        for row in rows
    }
    if len(signatures) != 1:
        raise RuntimeError(f"architecture mismatch: {signatures}")
    return rows


def values(rows: list[dict[str, str]], key: str) -> list[float]:
    return [float(row[key]) for row in rows]


def mean_sd(rows: list[dict[str, str]], key: str) -> tuple[float, float]:
    vals = values(rows, key)
    return statistics.mean(vals), statistics.stdev(vals) if len(vals) > 1 else 0.0


def latex_mean_sd(mean: float, sd: float, digits: int) -> str:
    return f"${mean:.{digits}f}\\pm{sd:.{digits}f}$"


def aggregate_random_per_haar_seed(
    rows: list[dict[str, str]], key: str
) -> tuple[float, float]:
    grouped: dict[int, list[float]] = defaultdict(list)
    for row in rows:
        grouped[int(row["init_seed"])].append(float(row[key]))
    per_seed = [statistics.mean(grouped[seed]) for seed in sorted(grouped)]
    return statistics.mean(per_seed), statistics.stdev(per_seed)


def membership_table(rows: list[dict[str, str]]) -> str:
    identity = [row for row in rows if row["protocol"] == "production_identity"]
    haar = [row for row in rows if row["protocol"] == "literal_haar_r"]
    matched = [row for row in rows if row["protocol"] == "matched_physical"]
    by_identity = {row["membership"]: row for row in identity}
    random_identity = [row for row in identity if row["membership"].startswith("random_")]
    learned_haar = [row for row in haar if row["membership"] == "learned"]
    contiguous_haar = [row for row in haar if row["membership"] == "contiguous"]
    random_haar = [row for row in haar if row["membership"].startswith("random_")]
    matched_unique = [row for row in matched if row["membership"] == "learned"]

    def single(row: dict[str, str], key: str, digits: int) -> str:
        return f"{float(row[key]):.{digits}f}"

    def group(rows_: list[dict[str, str]], key: str, digits: int) -> str:
        mean, sd = mean_sd(rows_, key)
        return latex_mean_sd(mean, sd, digits)

    def random_haar_group(key: str, digits: int) -> str:
        mean, sd = aggregate_random_per_haar_seed(random_haar, key)
        return latex_mean_sd(mean, sd, digits)

    lines = [
        "% Generated by docs/benchmark_tables/generate_sift128_membership_rotation_tables.py",
        "\\begin{table*}[!t]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\caption{Fixed-architecture membership and initialization control on SIFT1M/128b under flat ADC. All",
        "rows receive the same 12 dimension--budget pairs and vary only their physical",
        "membership or initialization; Identity is the default $R_0=I_d$ path. Haar",
        "values are mean$\\pm$standard deviation over 10 shared seeds; Random first",
        "averages five memberships per seed. Matched physical $W_0$ has zero",
        "cross-membership spread within each of three seeds, so its reported variation is",
        "across physical seeds. Lower $J$ and higher retrieval metrics are better.}",
        "\\label{tab:membership-rotation}",
        "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}llcrrrr@{}}",
        "\\toprule",
        "Initialization & Membership & Runs & $J$ & Recall@1 & Recall@10 & Overlap@1k \\\\",
        "\\midrule",
    ]
    learned = by_identity["learned"]
    contiguous = by_identity["contiguous"]
    lines.extend(
        [
            "Identity & Searched & 1 & "
            f"\\textbf{{{single(learned, 'reconstruction_error', 2)}}} & "
            f"\\textbf{{{single(learned, 'recall1', 4)}}} & "
            f"\\textbf{{{single(learned, 'recall10', 4)}}} & "
            f"\\textbf{{{single(learned, 'overlap1000', 4)}}} \\\\",
            "Identity & Contiguous & 1 & "
            f"{single(contiguous, 'reconstruction_error', 2)} & "
            f"{single(contiguous, 'recall1', 4)} & "
            f"{single(contiguous, 'recall10', 4)} & "
            f"{single(contiguous, 'overlap1000', 4)} \\\\",
            "Identity & Random & 5 & "
            f"{group(random_identity, 'reconstruction_error', 2)} & "
            f"{group(random_identity, 'recall1', 4)} & "
            f"{group(random_identity, 'recall10', 4)} & "
            f"{group(random_identity, 'overlap1000', 4)} \\\\",
            "\\midrule",
            "Haar $R_0$ & Searched & 10 & "
            f"{group(learned_haar, 'reconstruction_error', 2)} & "
            f"{group(learned_haar, 'recall1', 4)} & "
            f"{group(learned_haar, 'recall10', 4)} & "
            f"{group(learned_haar, 'overlap1000', 4)} \\\\",
            "Haar $R_0$ & Contiguous & 10 & "
            f"{group(contiguous_haar, 'reconstruction_error', 2)} & "
            f"{group(contiguous_haar, 'recall1', 4)} & "
            f"{group(contiguous_haar, 'recall10', 4)} & "
            f"{group(contiguous_haar, 'overlap1000', 4)} \\\\",
            "Haar $R_0$ & Random & $5\\times10$ & "
            f"{random_haar_group('reconstruction_error', 2)} & "
            f"{random_haar_group('recall1', 4)} & "
            f"{random_haar_group('recall10', 4)} & "
            f"{random_haar_group('overlap1000', 4)} \\\\",
            "\\midrule",
            "Matched physical $W_0$ & All three & $3\\times3$ & "
            f"{group(matched_unique, 'reconstruction_error', 2)} & "
            f"{group(matched_unique, 'recall1', 4)} & "
            f"{group(matched_unique, 'recall10', 4)} & "
            f"{group(matched_unique, 'overlap1000', 4)} \\\\",
            "\\bottomrule",
            "\\end{tabular*}",
            "\\end{table*}",
        ]
    )
    return "\n".join(lines) + "\n"


def restart_cost_table(rows: list[dict[str, str]], structure_path: Path) -> str:
    structure = json.loads(structure_path.read_text())
    structure_seconds = float(structure["meta"]["pipeline_time"])
    identity = [row for row in rows if row["protocol"] == "production_identity"]
    haar = [row for row in rows if row["protocol"] == "literal_haar_r"]
    learned = next(row for row in identity if row["membership"] == "learned")
    contiguous = next(row for row in identity if row["membership"] == "contiguous")
    contiguous_haar = sorted(
        (row for row in haar if row["membership"] == "contiguous"),
        key=lambda row: int(row["init_seed"]),
    )
    ten_restart = [contiguous, *contiguous_haar[:9]]

    learned_cost = structure_seconds + float(learned["training_seconds"])
    restart_cost = sum(float(row["training_seconds"]) for row in ten_restart)
    all_haar_cost = sum(float(row["training_seconds"]) for row in haar)

    def min_row(candidates: list[dict[str, str]], key: str) -> dict[str, str]:
        return min(candidates, key=lambda row: float(row[key]))

    def max_row(candidates: list[dict[str, str]], key: str) -> dict[str, str]:
        return max(candidates, key=lambda row: float(row[key]))

    restart_j = min_row(ten_restart, "reconstruction_error")
    restart_r1 = max_row(ten_restart, "recall1")
    restart_r10 = max_row(ten_restart, "recall10")
    all_j = min_row(haar, "reconstruction_error")
    all_r1 = max_row(haar, "recall1")
    all_r10 = max_row(haar, "recall10")

    lines = [
        "% Generated by docs/benchmark_tables/generate_sift128_membership_rotation_tables.py",
        "\\begin{table}[t]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2pt}",
        "\\caption{Compute-matched SIFT1M/128b comparison of the partition-induced physical",
        "initialization and random rotation restarts. Restarts use the selected descriptor",
        "without its search cost. For each displayed metric, a restart row reports the",
        "numerically most favorable final value in its candidate pool; Train sums 12-thread seconds over the",
        "pool. The all-Haar pool spans seven memberships and ten seeds. EPQ includes",
        "partition search and downstream refinement.}",
        "\\label{tab:restart-cost}",
        "\\begin{tabular*}{\\columnwidth}{@{\\extracolsep{\\fill}}lcrrrr@{}}",
        "\\toprule",
        "Strategy & Cand. & Train (s) & $J$ & R@1 & R@10 \\\\",
        "\\midrule",
        "Partition search + induced init & 1 & "
        f"\\textbf{{{learned_cost:.1f}}} & \\textbf{{{float(learned['reconstruction_error']):.0f}}} & "
        f"\\textbf{{{float(learned['recall1']):.4f}}} & \\textbf{{{float(learned['recall10']):.4f}}} \\\\",
        "Given arch.; identity + 9 Haar & 10 & "
        f"{restart_cost:.1f} & {float(restart_j['reconstruction_error']):.0f} & "
        f"{float(restart_r1['recall1']):.4f} & {float(restart_r10['recall10']):.4f} \\\\",
        "Given arch.; all Haar & 70 & "
        f"{all_haar_cost:.1f} & {float(all_j['reconstruction_error']):.0f} & "
        f"{float(all_r1['recall1']):.4f} & {float(all_r10['recall10']):.4f} \\\\",
        "\\bottomrule",
        "\\end{tabular*}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, required=True)
    parser.add_argument("--structure", type=Path, required=True)
    parser.add_argument("--paper-generated", type=Path, required=True)
    args = parser.parse_args()

    rows = load_rows(args.results)
    args.paper_generated.mkdir(parents=True, exist_ok=True)
    membership_path = args.paper_generated / "sift128_membership_rotation_table.tex"
    restart_path = args.paper_generated / "sift128_restart_cost_table.tex"
    membership_path.write_text(membership_table(rows))
    restart_path.write_text(restart_cost_table(rows, args.structure))
    print(
        json.dumps(
            {
                "membership_table": str(membership_path),
                "restart_cost_table": str(restart_path),
            }
        )
    )


if __name__ == "__main__":
    main()
